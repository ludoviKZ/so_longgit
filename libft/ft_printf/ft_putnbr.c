#include "../libft.h"

int	ft_putnbr(int n)
{
	int	ret;

	ret = 0;
	if (n < 0)
	{
		ret += (write(1, "-", 1));
		if (n == -2147483648)
		{
			ret += (write(1, "2", 1));
			n = -147483648;
		}
		n *= -1;
	}
	if (n > 9)
	{
		ret += (ft_putnbr((n / 10)));
		ret += (ft_putchar((n % 10) + 48));
	}
	else
		ret += (ft_putchar(n + 48));
	return (ret);
}
