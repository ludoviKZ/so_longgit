#include "libft.h"

int	ft_isalnum(int str)
{
	if (((str >= 'A') && (str <= 'Z')) || (
			(str >= 'a') && (str <= 'z')) || (
			(str >= '0') && (str <= '9')))
		return (1);
	return (0);
}
